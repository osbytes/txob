/**
 * The store contract run through each ORM adapter. Skipped unless TXOB_TEST_PG_URL is set;
 * needs `yarn test:prepare` (generates the Prisma Client) first.
 */
const connectionString = process.env.TXOB_TEST_PG_URL;

type Isolated = { tablePrefix: string; channel: string };

const isolated = (): Isolated => {
  const tablePrefix = `o${randomBytes(4).toString("hex")}_`;
  return { tablePrefix, channel: `${tablePrefix}wakeup` };
};

type OrmCase<TTx> = {
  name: string;
  /** Opens the ORM, creates txob's tables with its migration tooling, returns an adapter. */
  open(names: Isolated): Promise<{
    adapter: PgAdapter<TTx>;
    close(): Promise<void>;
    createWakeupEmitter?: () => ReturnType<typeof createPgWakeupEmitter>;
  }>;
};

const cases: OrmCase<any>[] = [
  {
    name: "drizzle (node-postgres)",
    open: async (names) => {
      const pool = new pg.Pool({ connectionString, max: 20 });
      const db = drizzleNodePostgres(pool);
      await migrate(drizzleAdapter(db), names);
      return { adapter: drizzleAdapter(db), close: () => pool.end() };
    },
  },
  {
    name: "drizzle (postgres.js)",
    open: async (names) => {
      const sql = postgres(connectionString!, { max: 20, onnotice: () => {} });
      const db = drizzlePostgresJs(sql);
      await migrate(drizzleAdapter(db), names);
      return { adapter: drizzleAdapter(db), close: () => sql.end() };
    },
  },
  {
    name: "kysely",
    open: async (names) => {
      const db = new Kysely<any>({
        dialect: new PostgresDialect({
          pool: new pg.Pool({ connectionString, max: 20 }),
        }),
      });
      await kyselyMigration(names).up(db);
      return { adapter: kyselyAdapter(db), close: () => db.destroy() };
    },
  },
  {
    name: "prisma",
    open: async (names) => {
      // Generated by `yarn test:prepare`; loaded here so other tests run without it
      const { PrismaClient } = await import("./prisma/generated/client.js");
      const prisma = new PrismaClient({
        adapter: new PrismaPg({ connectionString, max: 20 }),
      });
      const adapter = prismaAdapter(prisma);
      await migrate(adapter, names);
      return { adapter, close: () => prisma.$disconnect() };
    },
  },
  {
    name: "postgres.js",
    open: async (names) => {
      const sql = postgres(connectionString!, { max: 20, onnotice: () => {} });
      await migrate(postgresAdapter(sql), names);
      return {
        adapter: postgresAdapter(sql),
        close: () => sql.end(),
        createWakeupEmitter: () =>
          createPostgresWakeupEmitter(sql, { channel: names.channel }) as any,
      };
    },
  },
  {
    name: "sequelize",
    open: async (names) => {
      const sequelize = new Sequelize(connectionString!, {
        logging: false,
        pool: { max: 20 },
      });
      await sequelizeMigration(names).up(sequelize.getQueryInterface());
      return {
        adapter: sequelizeAdapter(sequelize),
        close: () => sequelize.close(),
      };
    },
  },
  {
    name: "knex",
    open: async (names) => {
      const db = knex({
        client: "pg",
        connection: connectionString,
        pool: { min: 0, max: 20 },
      });
      await knexMigration(names).up(db);
      return { adapter: knexAdapter(db), close: () => db.destroy() };
    },
  },
  {
    name: "typeorm",
    open: async (names) => {
      const dataSource = new DataSource({
        type: "postgres",
        url: connectionString,
        poolSize: 20,
        migrations: [typeormMigration(names)],
        migrationsTableName: `${names.tablePrefix}typeorm_migrations`,
      });
      await dataSource.initialize();
      await dataSource.runMigrations();
      return {
        adapter: typeormAdapter(dataSource),
        close: async () => {
          await dataSource.query(
            `DROP TABLE ${names.tablePrefix}typeorm_migrations`,
          );
          await dataSource.destroy();
        },
      };
    },
  },
];

describe.skipIf(!connectionString)("postgres ORM adapters", () => {
  const pool = new pg.Pool({ connectionString });
  afterAll(() => pool.end());

  const dropTables = (tablePrefix: string) =>
    pool.query(
      `DROP TABLE IF EXISTS ${tablePrefix}deliveries, ${tablePrefix}events, ${tablePrefix}rate_limit_claims; DROP FUNCTION IF EXISTS ${tablePrefix}notify`,
    );

  for (const orm of cases) {
    describe(orm.name, () => {
      runStoreContract(orm.name, async () => {
        const names = isolated();
        const { adapter, close, createWakeupEmitter } = await orm.open(names);
        const store = createPgStore({
          adapter,
          tablePrefix: names.tablePrefix,
        });
        return {
          store,
          transaction: (fn) => adapter.transaction(fn),
          getDeliveries: async () =>
            (await pool.query(`SELECT * FROM ${names.tablePrefix}deliveries`))
              .rows,
          getEvents: async () =>
            (
              await pool.query(
                `SELECT id, type, fanned_out_at FROM ${names.tablePrefix}events`,
              )
            ).rows,
          createWakeupEmitter:
            createWakeupEmitter ??
            (() =>
              createPgWakeupEmitter({
                listenClientConfig: { connectionString },
                channel: names.channel,
              })),
          teardown: async () => {
            await close();
            await dropTables(names.tablePrefix);
          },
        };
      });
    });
  }

  it("sends awkward array values through Knex intact", async () => {
    const db = knex({ client: "pg", connection: connectionString });
    try {
      const values = ['a"b', "c,d", "e\\f", "{g}", "NULL", "", " h ", null];
      const [row] = await knexAdapter(db).query(
        "SELECT $1::text[] AS values, $2::int[] AS ints",
        [values, [1, null, -3]],
      );
      expect(row).toEqual({ values, ints: [1, null, -3] });
    } finally {
      await db.destroy();
    }
  });

  describe("prisma migrate", () => {
    // Prisma drops tables its schema doesn't model, unless they're in a schema it doesn't manage
    it("leaves txob's tables alone in their own Postgres schema", async () => {
      const database = `prisma_${randomBytes(4).toString("hex")}`;
      await pool.query(`CREATE DATABASE ${database}`);
      const url = new URL(connectionString!);
      url.pathname = `/${database}`;
      const db = new pg.Pool({ connectionString: url.toString() });
      try {
        await db.query(
          `CREATE TABLE "Note" (id SERIAL PRIMARY KEY, body TEXT NOT NULL)`,
        );
        await migrate(db, { schema: "txob" });
        const diff = () =>
          promisify(execFile)(
            "npx",
            [
              "prisma",
              "migrate",
              "diff",
              "--from-config-datasource",
              "--to-schema",
              "schema.prisma",
              "--script",
            ],
            {
              cwd: fileURLToPath(new URL("./prisma", import.meta.url)),
              env: {
                ...process.env,
                TXOB_TEST_PRISMA_DIFF_URL: url.toString(),
              },
            },
          );
        expect((await diff()).stdout).toContain("empty migration");
        // Sanity check: in Prisma's schema, the same tables would be dropped
        await migrate(db, { schema: "public" });
        expect((await diff()).stdout).toContain('DROP TABLE "txob_events"');
      } finally {
        await db.end();
        await pool.query(`DROP DATABASE ${database}`);
      }
    }, 60_000);
  });

  describe("drizzle schema", () => {
    // Drizzle Kit's migration for txobTables() must create what `migrate` creates
    it("matches the tables created by migrate", async () => {
      const { generateDrizzleJson, generateMigration } =
        await import("drizzle-kit/api");
      const fromDrizzle = isolated();
      const fromMigrate = isolated();
      try {
        const statements = await generateMigration(
          generateDrizzleJson({}),
          generateDrizzleJson(txobTables(fromDrizzle)),
        );
        for (const statement of [
          ...statements,
          ...getWakeupTriggerStatements(fromDrizzle),
        ]) {
          await pool.query(statement);
        }
        await migrate(pool, fromMigrate);
        const [drizzleSchema, migrateSchema] = await Promise.all([
          describeTables(pool, fromDrizzle.tablePrefix),
          describeTables(pool, fromMigrate.tablePrefix),
        ]);
        expect(drizzleSchema).toEqual(migrateSchema);
      } finally {
        await dropTables(fromDrizzle.tablePrefix);
        await dropTables(fromMigrate.tablePrefix);
      }
    });
  });
});

/** Columns, indexes and constraints of txob's tables, with the prefix replaced. */
const describeTables = async (pool: pg.Pool, prefix: string) => {
  const unprefix = (value: unknown) =>
    JSON.parse(JSON.stringify(value).replaceAll(prefix, "<p>"));
  const columns = await pool.query(
    `SELECT table_name, column_name, data_type, is_nullable, column_default
     FROM information_schema.columns WHERE table_name LIKE $1
     ORDER BY table_name, column_name`,
    [`${prefix}%`],
  );
  const indexes = await pool.query(
    `SELECT tablename, indexname, indexdef FROM pg_indexes WHERE tablename LIKE $1
     ORDER BY indexname`,
    [`${prefix}%`],
  );
  const constraints = await pool.query(
    `SELECT conrelid::regclass::text AS table_name, contype,
       pg_get_constraintdef(oid) AS definition
     FROM pg_constraint WHERE conrelid::regclass::text LIKE $1
     ORDER BY 1, 2, 3`,
    [`${prefix}%`],
  );
  return unprefix({
    columns: columns.rows,
    // Constraint-backed index names differ between tools; compare their definitions
    indexes: indexes.rows
      .map((r) => r.indexdef.replace(/INDEX \S+ ON/, "INDEX ON"))
      .sort(),
    constraints: constraints.rows,
  });
};
